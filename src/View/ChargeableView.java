    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            int tipo = jComboBox1.getSelectedIndex();
            if (tipo == 2) {
                int items = Integer.parseInt(jTextField3.getText().trim());
                double chargePerItem = Double.parseDouble(jTextField2.getText().trim());
                controller.regPackaging(items, chargePerItem);
            } else {
                double km = Double.parseDouble(jTextField1.getText().trim());
                String id = (tipo == 0 ? "B" : "V") + (controller.getCantidad() + 1);
                if (tipo == 0) {
                    controller.regBikeDelivery(id, km);
                } else {
                    controller.regVanDelivery(id, km);
                }
            }
            Model.Chargeable ultimo = controller.getElemento(controller.getCantidad() - 1);
            jLabel5.setText(ultimo.label() + ": " + ultimo.calculateCharge()
                    + " | Total: " + controller.calcTotalGeneral());
            clearFields();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Ingrese valores numericos validos.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

